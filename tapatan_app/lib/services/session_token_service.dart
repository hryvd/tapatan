import 'dart:convert';
import 'dart:typed_data';
import 'dart:math';
import 'package:shared_preferences/shared_preferences.dart';

// ── Session Token ─────────────────────────────────────────────────────────

/// A replay-protected session token wrapping the card's ECDSA signature.
///
/// Built from the output of [JcopApduService.sendChallengeResponse].
/// Each token is unique (bound to a fresh [phoneChallenge] and [cardNonce])
/// and expires after [kSessionTokenExpiryMinutes] minutes.
///
/// This satisfies JCOP plan Phase B.2 — tokens must be:
///   - Bound to a freshly-generated random challenge (not predictable)
///   - Time-scoped (expiry embedded)
///   - Signed with the card's private key (verified by backend)
class SessionToken {
  /// Unique identifier for this token session.
  final String tokenId;

  /// The card's ECDSA P-256 signature over (cardNonce || phoneChallenge).
  final Uint8List cardSignature;

  /// The phone-generated random challenge used in this session.
  final Uint8List phoneChallenge;

  /// The card-generated nonce received via GET CHALLENGE.
  final Uint8List cardNonce;

  /// The card's hardware UID — used to verify card identity at the backend.
  final String cardUid;

  /// When this token was created (UTC).
  final DateTime createdAt;

  /// Whether this token has already been consumed (used once rule).
  bool used;

  SessionToken({
    required this.tokenId,
    required this.cardSignature,
    required this.phoneChallenge,
    required this.cardNonce,
    required this.cardUid,
    required this.createdAt,
    this.used = false,
  });

  /// Serializes this token to a JSON string for transmission to the backend.
  String toJson() {
    return jsonEncode({
      'token_id': tokenId,
      'card_signature': _bytesToHex(cardSignature),
      'phone_challenge': _bytesToHex(phoneChallenge),
      'card_nonce': _bytesToHex(cardNonce),
      'card_uid': cardUid,
      'created_at': createdAt.toIso8601String(),
      'version': '1',
    });
  }

  static String _bytesToHex(Uint8List bytes) =>
      bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join('');
}

// ── Session Token Service ─────────────────────────────────────────────────

/// Token expiry — tokens are valid for 5 minutes.
/// After this time the backend will reject them even if the signature is valid.
const int kSessionTokenExpiryMinutes = 5;

/// Maximum number of recently used token IDs to persist (replay protection).
const int kMaxUsedTokenHistory = 50;

/// Key for persisting used token IDs in SharedPreferences.
const String kPrefUsedTokenIds = 'jcop_used_token_ids';

/// Manages session token creation, validation, and replay protection.
///
/// This is the app-side implementation of JCOP plan Phase B.2:
/// session tokens bound to a fresh challenge, time-scoped, and protected
/// against replay via a persisted list of consumed token IDs.
class SessionTokenService {
  // ── Token Construction ───────────────────────────────────────────────────

  /// Builds a [SessionToken] from the result of a JCOP challenge-response exchange.
  ///
  /// [cardSignature]: ECDSA signature bytes from INTERNAL AUTHENTICATE.
  /// [phoneChallenge]: the random challenge generated by the phone.
  /// [cardNonce]: the nonce received from GET CHALLENGE.
  /// [cardUid]: the card's hardware UID (from readCardUid).
  ///
  /// Returns a fresh [SessionToken] with a unique ID and current timestamp.
  static SessionToken buildToken({
    required Uint8List cardSignature,
    required Uint8List phoneChallenge,
    required Uint8List cardNonce,
    required String cardUid,
  }) {
    final tokenId = _generateTokenId();
    return SessionToken(
      tokenId: tokenId,
      cardSignature: cardSignature,
      phoneChallenge: phoneChallenge,
      cardNonce: cardNonce,
      cardUid: cardUid,
      createdAt: DateTime.now().toUtc(),
    );
  }

  // ── Token Validation ─────────────────────────────────────────────────────

  /// Returns true if the token is within its expiry window.
  ///
  /// Time-based expiry prevents long-lived tokens from being captured
  /// and replayed later (e.g., via an NFC relay attack).
  static bool isTokenFresh(SessionToken token) {
    final age = DateTime.now().toUtc().difference(token.createdAt);
    return age.inMinutes < kSessionTokenExpiryMinutes;
  }

  /// Returns true if the token has NOT been used yet.
  ///
  /// In-memory check only — for cross-session protection use [wasTokenUsedPersisted].
  static bool isTokenUnused(SessionToken token) => !token.used;

  /// Full validity check: token must be fresh AND unused.
  static bool isTokenValid(SessionToken token) =>
      isTokenFresh(token) && isTokenUnused(token);

  /// Returns the number of seconds remaining before this token expires.
  static int secondsUntilExpiry(SessionToken token) {
    final expiryTime = token.createdAt
        .add(Duration(minutes: kSessionTokenExpiryMinutes));
    final remaining = expiryTime.difference(DateTime.now().toUtc()).inSeconds;
    return remaining.clamp(0, kSessionTokenExpiryMinutes * 60);
  }

  // ── Replay Protection ────────────────────────────────────────────────────

  /// Marks a token as used (in-memory) and persists the token ID.
  ///
  /// Call this immediately after sending the token to the backend for verification.
  /// Subsequent calls to [wasTokenUsedPersisted] with this token ID will return true.
  static Future<void> markTokenUsed(SessionToken token) async {
    token.used = true;
    await _persistUsedTokenId(token.tokenId);
  }

  /// Checks whether a token ID was previously used (persisted replay protection).
  ///
  /// Returns true if the token ID is found in the persisted used-token history.
  static Future<bool> wasTokenUsedPersisted(String tokenId) async {
    final usedIds = await _loadUsedTokenIds();
    return usedIds.contains(tokenId);
  }

  // ── Persistence ──────────────────────────────────────────────────────────

  static Future<void> _persistUsedTokenId(String tokenId) async {
    final prefs = await SharedPreferences.getInstance();
    final usedIds = await _loadUsedTokenIds();

    // Prepend new ID and trim to max history size (bounded memory usage)
    final updated = [tokenId, ...usedIds].take(kMaxUsedTokenHistory).toList();
    await prefs.setStringList(kPrefUsedTokenIds, updated);
  }

  static Future<List<String>> _loadUsedTokenIds() async {
    final prefs = await SharedPreferences.getInstance();
    return prefs.getStringList(kPrefUsedTokenIds) ?? [];
  }

  /// Clears the persisted token history (use during logout or card re-registration).
  static Future<void> clearTokenHistory() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.remove(kPrefUsedTokenIds);
  }

  // ── Token ID Generation ──────────────────────────────────────────────────

  static String _generateTokenId() {
    const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
    final rng = Random.secure();
    final suffix = List.generate(
      12,
      (_) => chars[rng.nextInt(chars.length)],
    ).join();
    return 'TKN_${DateTime.now().millisecondsSinceEpoch}_$suffix';
  }
}
